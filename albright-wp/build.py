# ── the WordPress.com fallback route must publish the SAME page, minus styling.
def md_item(r):
    bits=[f'**{r["item_no"]}. {r["title"]}**', "", r["gloss"], ""]
    if r["duplicate_or_original"].startswith("DUPLICATE"):
        bits += [f'> {r["duplicate_or_original"]}', ""]
    if r["status"]=="NOT READ":
        bits += ["> We have not opened this document. Nothing on this page is quoted from it.", ""]
    bits += [f'{r["creator"]} · {r["date_created"]} · {r["institution"]}']
    if r["stable_item_url"]: bits += [f'<{r["stable_item_url"]}>']
    bits += [f'Rights, in the institution\'s words: "{r["rights_statement_verbatim"]}"']
    if r["filename"].endswith(".jpg"):
        bits += [f'Image file: `media/{r["filename"]}` — {r["status"]}',
                 f'Credit: {r["required_credit"]}',
                 f'Alt text: {r["alt_text"]}']
    return "\n".join(bits)+"\n"

