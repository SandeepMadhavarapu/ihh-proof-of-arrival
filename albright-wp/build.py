questions=[" ".join(q.split()) for q in re.findall(r'^\d+\.\s+(.+?)(?=\n\d+\.|\Z)', qm.group(1), re.M|re.S)]
activities=[(" ".join(t.split())," ".join(b.split()))
            for t,b in re.findall(r'\*\*\d+\.\s*(.+?)\*\*\s*(.+?)(?=\n\*\*\d+\.|\Z)', qm.group(2), re.M|re.S)]

quote=re.search(r'\*\*First-person quotation \((.+?)\):\*\*\n> (.+?)\n\n', md, re.S)
# copy.md labels the slot "(one, as reported by X)". Strip the "one," counter so the
# rendered cite does not read "as reported by one, as reported by X".
