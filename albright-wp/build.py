quote_text = " ".join(quote.group(2).replace("\n>","").split())

anchor=rows[0]
E=html.escape
nrows=len(rows)
bookno=next((r["item_no"] for r in rows
             if r["kind"]=="book" and "Prague Winter" in r["title"]), str(nrows))

def source_item(r):
    is_img = r["filename"].endswith(".jpg")
    if is_img:
        absent = "NOT DOWNLOADED" in r["status"]
        if absent:
            # Never emit a live <img> for a file the package does not contain: it renders
            # as a broken image the moment the block is pasted. Show a labelled slot and
            # leave the real tag commented out for the volunteer to switch on.
            thumb=(f'<span class="th ph-th"><span>Image not supplied &mdash; save it as '
                   f'<code>media/{E(r["filename"])}</code>, then replace this block with '
                   f'the commented-out tag below</span></span>\n'
                   f'      <!-- <img class="th" src="media/{E(r["filename"])}" '
                   f'alt="{E(r["alt_text"])}" loading="lazy"> -->')
            note=""
        else:
            thumb=(f'<img class="th" src="media/{E(r["filename"])}" alt="{E(r["alt_text"])}" '
                   f'loading="lazy" decoding="async">')
            note=""
    else:
        thumb=f'<p class="kindmark">{E(r["kind"])}</p>'
        note=""
    dup=(f'<p class="dupe">{E(r["duplicate_or_original"])}</p>'
         if r["duplicate_or_original"].startswith("DUPLICATE") else "")
    unread=('<p class="unread">We have not opened this document. Nothing on this page is '
            'quoted from it.</p>') if r["status"]=="NOT READ" else ""
    link=(f'<a href="{E(r["stable_item_url"])}" rel="noopener">{E(r["institution"])}</a>'
          if r["stable_item_url"] else E(r["institution"]))
    return f'''    <li class="src-item">
      {thumb}{note}
      <h3 class="src-h">{E(r["title"])}</h3>
      <p class="gloss">{E(r["gloss"])}</p>
      {dup}{unread}
      <p class="meta">{E(r["creator"])} &middot; {E(r["date_created"])} &middot; {link}</p>
      <p class="rights"><b>Rights, in the institution&rsquo;s words:</b> {E(r["rights_statement_verbatim"])}</p>
    </li>'''

secs="\n".join(
 f'''  <details class="sec"{' open' if i==0 else ''}>
    <summary><h3>{E(t)}</h3></summary>
    <p>{b}</p>
  </details>''' for i,(t,b) in enumerate(sections))

qs="\n".join(f"      <li>{q}</li>" for q in questions)
acts="\n".join(f"      <li><b>{t}</b> {b}</li>" for t,b in activities)
srcs="\n".join(source_item(r) for r in rows)

