#!/usr/bin/env python3
"""Write the "In the collection" summary on site/index.html from the repository itself.

    python3 tools/build_profile.py --all && python3 tools/build_site_pages.py   # first
    python3 tools/build_home.py

Every number is counted from files, never typed by hand, so it cannot drift:
  profiles  - slugs in site-data/published.json
  sources   - source items drawn on the published profile pages (site/<slug>.html)
  checked   - statements from IHH's own inductee pages checked in review/workstream-1/evidence
  outside   - interviews and recordings in site-data/sources/*.json (preview placeholders excluded)
  new       - approved entries in site-data/new-at-the-museum.json
A feature is mentioned only if it is switched on in this build (Margin Notes: adapter != none).
Only the block between the collection-summary markers is rewritten.
"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
START = "<!-- collection-summary:start (generated by tools/build_home.py; edit the script, not this block) -->"
END = "<!-- collection-summary:end -->"


def load(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return json.load(f)


def counts():
    slugs = load("site-data/published.json")["published"]
    sources = 0
    for s in slugs:
        with open(os.path.join(SITE, f"{s}.html"), encoding="utf-8") as f:
            sources += len(re.findall(r'class="src-item', f.read()))
    checked = 0
    for path in glob.glob(os.path.join(ROOT, "review", "workstream-1", "evidence", "*.json")):
        with open(path, encoding="utf-8") as f:
            checked += len(json.load(f)["rows"])
    outside = 0
    for path in glob.glob(os.path.join(ROOT, "site-data", "sources", "*.json")):
        with open(path, encoding="utf-8") as f:
            outside += sum(1 for x in json.load(f)["sources"] if not x.get("placeholder"))
    new = len(load("site-data/new-at-the-museum.json")["entries"])
    notes_on = load("site-data/visitor-voices.json").get("adapter", "none") != "none"
    return dict(profiles=len(slugs), sources=sources, checked=checked, outside=outside, new=new,
                notes_on=notes_on)


def block(c):
    items = [
        f'<li><b>{c["profiles"]}</b> inductee profiles, each with the story of an arrival, the '
        'records behind it, and questions to talk about. <a href="inductees.html">Browse them</a>.</li>',
        f'<li><b>{c["sources"]}</b> sources listed and linked on those profiles, each with its holding '
        'institution and its rights statement in the institution&rsquo;s own words.</li>',
        f'<li><b>{c["checked"]}</b> statements from the inductee pages on immigranthallofhonor.org '
        'checked against outside sources while these profiles were researched.</li>',
        f'<li><b>{c["outside"]}</b> interviews and recordings held by other archives, linked from the '
        'profiles until their holders give permission to show them here.</li>',
    ]
    if c["new"]:
        items.append(f'<li><b>{c["new"]}</b> new discoveries checked and approved since launch. '
                     '<a href="new.html">See what&rsquo;s new</a>.</li>')
    else:
        items.append('<li><a href="new.html">New at the Museum</a> will list each new discovery once a '
                     'person on our team has checked it against its source. None has been added yet.</li>')
    if c["notes_on"]:
        items.append('<li>Visitors can leave a note on the exact passage that prompted it; a curator '
                     'reads every note before it appears.</li>')
    body = "\n    ".join(items)
    return (f"{START}\n<section class=\"band quiet\">\n  <h2>In the collection</h2>\n"
            f"  <ul class=\"collection-facts\">\n    {body}\n  </ul>\n</section>\n{END}")


def main():
    path = os.path.join(SITE, "index.html")
    with open(path, encoding="utf-8") as f:
        page = f.read()
    i, j = page.find(START), page.find(END)
    if i < 0 or j < i:
        raise SystemExit("site/index.html: collection-summary markers missing")
    c = counts()
    page = page[:i] + block(c) + page[j + len(END):]
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(page)
    print("site/index.html collection summary:", c)


if __name__ == "__main__":
    main()
