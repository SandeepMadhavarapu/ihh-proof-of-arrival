#!/usr/bin/env python3
"""Write site/robots.txt and site/sitemap.xml for the demonstration build.

    python3 tools/build_site_meta.py

The demonstration is published at BASE (GitHub Pages). It is a student prototype for the
Immigrant Hall of Honor, not IHH's official website, so robots.txt asks search engines not to
crawl it: the prototype must never compete with immigranthallofhonor.org in search results.
sitemap.xml lists every page so the package is complete if IHH hosts it themselves; change BASE
(and the robots rule) when that happens. Both files are generated: edit this script, not them.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
BASE = "https://sandeepmadhavarapu.github.io/ihh-proof-of-arrival/"
SKIP = {"404.html"}


def main():
    pages = sorted(f for f in os.listdir(SITE) if f.endswith(".html") and f not in SKIP)
    pages.remove("index.html")
    pages.insert(0, "index.html")
    urls = "\n".join(f"  <url><loc>{BASE}{p}</loc></url>" for p in pages)
    sitemap = ('<?xml version="1.0" encoding="UTF-8"?>\n'
               "<!-- Generated by tools/build_site_meta.py. Demonstration build of a student prototype for\n"
               "     the Immigrant Hall of Honor; not the official IHH website (immigranthallofhonor.org). -->\n"
               '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
               f"{urls}\n</urlset>\n")
    robots = ("# Generated by tools/build_site_meta.py.\n"
              "# Student prototype built for the Immigrant Hall of Honor (ChallengeX 2026).\n"
              "# Not the official IHH website: https://immigranthallofhonor.org/\n"
              "# Kept out of search engines so it never competes with IHH's own site.\n"
              "User-agent: *\nDisallow: /\n")
    with open(os.path.join(SITE, "sitemap.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(sitemap)
    with open(os.path.join(SITE, "robots.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(robots)
    print(f"site/sitemap.xml: {len(pages)} pages under {BASE}; site/robots.txt: disallow all")


if __name__ == "__main__":
    main()
