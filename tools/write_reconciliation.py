#!/usr/bin/env python3
"""Write handover/<slug>/ihh-content-reconciliation.md from a reviewed evidence file.

    python3 tools/write_reconciliation.py review/workstream-1/evidence/*.json

Each evidence file holds the IHH claims, a status per row, the sources, the exact
quoted spans and a note. Edit the JSON, then re-run; never edit the note by hand.
The notes are private editorial working files and must never be linked from site/.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATUSES = ["CONFIRMED", "PARTLY CONFIRMED", "CORRECTION SUGGESTED", "NOT VERIFIED", "NO CLAIM"]
NEEDS_SPANS = {"CONFIRMED", "PARTLY CONFIRMED", "CORRECTION SUGGESTED"}
SECTIONS = ["Facts", "Achievements", "Honours"]


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ").strip()


def check(doc):
    for line, row in doc["rows"].items():
        where = f"{doc['slug']} {line}"
        assert row["status"] in STATUSES, f"{where}: unknown status {row['status']!r}"
        assert row["section"] in SECTIONS, f"{where}: unknown section {row['section']!r}"
        assert row["note"].strip(), f"{where}: every row needs a note"
        if row["status"] in NEEDS_SPANS:
            assert row["evidence"], f"{where}: {row['status']} needs at least one quoted span"
        else:
            assert not row["evidence"], f"{where}: {row['status']} must not carry spans"
        for key, span in row["evidence"]:
            assert key in doc["sources"], f"{where}: unknown source {key}"
            assert span.strip(), f"{where}: empty span"


def table(doc, lines):
    out = ["| IHH line | Claim under review | Status | Source | Exact quoted span(s) | Retrieved | Note |",
           "|---|---|---|---|---|---|---|"]
    for line in lines:
        row = doc["rows"][line]
        keys = list(dict.fromkeys(k for k, _ in row["evidence"]))
        many = len(keys) > 1
        ref = lambda k: f"[{keys.index(k) + 1}] " if many else ""
        sources = "<br>".join(f"{ref(k)}[{cell(doc['sources'][k][0])}]({doc['sources'][k][1]})" for k in keys) or "—"
        spans = "<br>".join(f"{ref(k)}“{cell(s)}”" for k, s in row["evidence"]) or "—"
        date = doc["retrieved"] if row["evidence"] else "—"
        out.append(f"| {line} | {cell(row['claim'])} | **{row['status']}** | {sources} | {spans} | {date} | {cell(row['note'])} |")
    return out


def render(doc):
    check(doc)
    rows = doc["rows"]
    counts = {s: sum(r["status"] == s for r in rows.values()) for s in STATUSES}
    tally = " · ".join(f"{s} {counts[s]}" for s in STATUSES)
    header = doc["header"]
    out = [f"# {doc['title']}", "", header[0], "",
           f"**Rows by status ({len(rows)} rows):** {tally}.", ""]
    for para in header[1:]:
        out += [para, ""]
    out += [f"**Evidence pass, {doc['retrieved']}.** Every row below carries its own status, source, exact quoted span(s), "
            "retrieval date and note. Each span was checked against the live source page after collapsing whitespace "
            "(page text, or the text layer of a PDF). This note is generated by `tools/write_reconciliation.py` from "
            f"`review/workstream-1/evidence/{doc['slug']}.json`; correct the evidence file, not this note.", ""]
    for section in SECTIONS:
        out += [f"## {section}", ""]
        lines = sorted((l for l, r in rows.items() if r["section"] == section), key=lambda l: int(l[1:]))
        if lines:
            out += table(doc, lines)
        else:
            out.append(doc["empty_sections"].get(section, "No entries in the retrieved IHH page."))
        out.append("")
    if doc.get("profile_notes"):
        out += ["## Notes on our own profile — human review only", "",
                "These do not authorize any change to `copy.md`; they are for the team lead to decide.", ""]
        out += [f"- {note}" for note in doc["profile_notes"]] + [""]
    out += [doc["tail"].rstrip("\n"), ""]
    return "\n".join(out)


def main(paths):
    if not paths:
        sys.exit(__doc__)
    for path in paths:
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
        target = os.path.join(ROOT, "handover", doc["slug"], "ihh-content-reconciliation.md")
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(render(doc))
        print(f"wrote {os.path.relpath(target, ROOT)} ({len(doc['rows'])} rows)")


if __name__ == "__main__":
    main(sys.argv[1:])
